export function squadFor(teamId: string): SquadPlayer[] {
  const team = getTeam(teamId);
  const featured: SquadPlayer[] = team.players.map((p) => ({
    id: p.id,
    name: p.name,
    pos: p.pos,
    num: NUM[p.id] ?? 10,
  }));
  const seen = new Set(featured.map((p) => p.id));
  const rest = (EXTRA[teamId] ?? []).filter((p) => !seen.has(p.id) && !seen.has(p.name));
  const names = new Set(featured.map((p) => p.name));
  const unique = rest.filter((p) => {
    if (names.has(p.name)) return false;
    names.add(p.name);
    return true;
  });
  return [...featured, ...unique].slice(0, 16);
}

export function findSquadPlayer(teamId: string, id: string): SquadPlayer | undefined {
  return squadFor(teamId).find((p) => p.id === id);
}
